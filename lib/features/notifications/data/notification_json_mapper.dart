import '../models/app_notification.dart';
import '../../../core/network/utc_timestamp.dart';

/// The kebab-case payload, before context lookup. Bad required fields are
/// errors, not an empty inbox or a received notice with an invented date.
class NotificationRecord {
  NotificationRecord.fromJson(
    Map<String, Object?> json, {
    required String ownerId,
  }) : id = positiveNotificationId(json['id']),
       userId = notificationUserId(json['user-id']),
       typeId = positiveNotificationId(json['type']),
       receivedAt = _receivedDate(json['notification-date']),
       isRead = switch (json['read']) {
         final bool value => value,
         _ => throw const FormatException('Expected a read flag'),
       },
       activityId = json['event'] == null
           ? null
           : positiveNotificationId(json['event']),
       requestDate = _requestDate(json['request-date']),
       personId = json['friend-id'] == null
           ? null
           : notificationUserId(json['friend-id']) {
    if (userId != ownerId) {
      throw const FormatException('Notification belongs to another account');
    }
  }
  final String id;
  final String userId;
  final String typeId;
  final DateTime receivedAt;
  final bool isRead;
  final String? activityId;
  final String? personId;
  final DateTime? requestDate;
}

String positiveNotificationId(Object? value) {
  if (value is int && value > 0) return '$value';
  throw const FormatException('Expected a positive notification reference');
}

String notificationUserId(Object? value) {
  if (value is String &&
      RegExp(r'^[0-9a-fA-F]{8}(-[0-9a-fA-F]{4}){3}-[0-9a-fA-F]{12}$')
          .hasMatch(value) &&
      value != '00000000-0000-0000-0000-000000000000') {
    return value.toLowerCase();
  }
  throw const FormatException('Expected a real user UUID');
}

DateTime _receivedDate(Object? value) {
  final parsed = value is String ? DateTime.tryParse(value) : null;
  if (parsed == null || parsed.year < 2) {
    throw const FormatException('Expected a received date');
  }
  // TODO(DP-039): pgtype.Timestamp can omit a zone. Preserve explicit offsets;
  // a zone-less date remains local until the API defines its time-zone policy.
  return parsed;
}

Map<String, NotificationType> notificationTypesFromJson(Object? decoded) {
  if (decoded is! List<Object?>) {
    throw const FormatException('Expected a notification type list');
  }
  final types = <String, NotificationType>{};
  for (final item in decoded) {
    if (item is! Map<String, Object?> ||
        item['name'] is! String ||
        (item['name'] as String).trim().isEmpty) {
      throw const FormatException('Expected a notification type ID and name');
    }
    final id = positiveNotificationId(item['id']);
    if (types.containsKey(id)) throw const FormatException('Duplicate type ID');
    final name = (item['name'] as String)
        .trim()
        .toLowerCase()
        .replaceAll('ó', 'o')
        .replaceAll('ò', 'o');
    // IDs are generated by PostgreSQL. Only these category names are defined,
    // not six social subtypes with fixed integer codes.
    types[id] = switch (name) {
      'social' => NotificationType.socialUpdate,
      'recomanacio' => NotificationType.recommendation,
      'recordatori' => NotificationType.reminder,
      // Created by the backend for each person signed up when the creator
      // cancels an activity (#46, #47).
      'cancelacio' => NotificationType.activityCancelled,
      _ => NotificationType.other,
    };
  }
  return Map.unmodifiable(types);
}

// An absent/invalid optional reference never makes a generic notice actionable.
DateTime? _requestDate(Object? value) {
  if (value == null) return null;
  try {
    // TODO(DP-066): request-date is a zone-less SQL timestamp representing the
    // same UTC instant as date-sent. Never interpret it in the device timezone.
    return utcTimestamp(value, allowMissingZone: true);
  } on FormatException {
    return null;
  }
}
